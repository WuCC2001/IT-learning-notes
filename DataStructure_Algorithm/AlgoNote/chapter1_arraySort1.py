
# 排序算法的分类
# 排序算法可以按照不同的标准进行分类：

# 按照时间复杂度分类
    # 简单排序算法：时间复杂度为 O(n^2)，如冒泡排序、选择排序、插入排序
    # 高级排序算法：时间复杂度为 O(nlogn)，如快速排序、归并排序、堆排序
    # 线性排序算法：时间复杂度为 O(n)，如计数排序、桶排序、基数排序
# 按照空间复杂度分类
    # 原地排序算法：空间复杂度为 O(1)，如冒泡排序、选择排序、插入排序、快速排序、堆排序
    # 非原地排序算法：空间复杂度为 O(n) 或更高，如归并排序、计数排序、桶排序、基数排序
# 按照稳定性分类
    # 稳定排序算法：相等元素的相对顺序在排序后保持不变，如冒泡排序、插入排序、归并排序、计数排序、桶排序、基数排序
    # 不稳定排序算法：相等元素的相对顺序在排序后可能改变，如选择排序、快速排序、堆排序


# 排序算法的评价指标
# 评价一个排序算法的好坏，主要从以下几个方面考虑：
    # 时间复杂度：算法执行所需的时间，包括最好情况、最坏情况和平均情况
    # 空间复杂度：算法执行所需的额外空间（不包括输入数据本身）
    # 稳定性：相等元素的相对顺序是否保持不变
    # 原地性：是否需要在原数组之外开辟额外空间


# 常见的排序算法包括：

# 冒泡排序：通过相邻元素比较和交换，将最大元素逐步「冒泡」到数组末尾
# 选择排序：每次从未排序区间选择最小元素，放到已排序区间末尾
# 插入排序：将未排序区间的元素插入到已排序区间的合适位置
# 希尔排序：先按一定间隔分组进行插入排序，逐步缩小间隔，最后整体进行插入排序

# 归并排序：将数组分成两半，分别排序后合并
# 快速排序：选择一个基准元素，将数组分为两部分，递归排序
# 堆排序：利用堆这种数据结构进行排序

# 计数排序：统计每个元素出现的次数，按顺序输出
# 桶排序：将元素分到有限数量的桶中，对每个桶单独排序
# 基数排序：按照元素的位数进行排序


# 排序算法的选择策略
# 在实际应用中，选择合适的排序算法需要考虑以下因素：

# 数据规模
    # 小规模数据（n < 50）：可以使用简单排序算法，如插入排序
    # 中等规模数据（50 ≤ n < 1000）：推荐使用快速排序或归并排序
    # 大规模数据（n ≥ 1000）：优先考虑快速排序、归并排序或堆排序
# 数据特征
    # 基本有序：插入排序效率较高
    # 数据分布均匀：快速排序效率较高
    # 数据范围较小：计数排序或桶排序可能更高效
    # 数据有大量重复：三路快速排序或计数排序更合适
# 环境约束
    # 空间限制：选择原地排序算法
    # 稳定性要求：选择稳定排序算法
    # 硬件环境：考虑缓存友好性和并行化潜力
# 实际应用场景
    # 系统排序：通常使用快速排序或归并排序的混合算法
    # 外部排序：使用归并排序
    # 实时系统：优先考虑时间复杂度稳定的算法
    # 内存受限环境：选择空间复杂度低的算法


# 冒泡排序（Bubble Sort）

# 基本思想：
# 通过相邻元素的比较与交换，将较大的元素逐步「冒泡」到数组末尾，较小的元素自然「下沉」到数组开头。

# 冒泡排序的名字来源于这个过程：就像水中的气泡从底部向上浮到水面一样，较大的元素会逐步移动到数组的末尾。

class Solution:
    def bubbleSort(self, nums: list[int]) -> list[int]:
        """冒泡排序算法实现"""
        n = len(nums)
        # 外层循环控制趟数，每一趟将当前未排序区间的最大值「冒泡」到末尾
        for i in range(n - 1):
            swapped = False  # 记录本趟是否发生过交换
            # 内层循环负责相邻元素两两比较，将较大值后移
            for j in range(n - i - 1):
                # 如果前一个元素大于后一个元素，则交换
                if nums[j] > nums[j + 1]:
                    nums[j], nums[j + 1] = nums[j + 1], nums[j]
                    swapped = True  # 发生了交换
            # 如果本趟没有发生任何交换，说明数组已经有序，可以提前结束
            if not swapped:
                break
        return nums  # 返回排序后的数组

    def sortArray(self, nums: list[int]) -> list[int]:
        """排序数组的接口，调用冒泡排序"""
        return self.bubbleSort(nums)


# 选择排序（Selection Sort）

# 基本思想：
# 将数组分为两个区间：左侧为已排序区间，右侧为未排序区间。每趟从未排序区间中选择最小的元素，放到已排序区间的末尾。

# 选择排序是一种简单直观的排序算法，实现简单，易于理解。

class Solution:
    def selectionSort(self, nums: list[int]) -> list[int]:
        n = len(nums)
        for i in range(n - 1):
            # 找到未排序区间中最小元素的位置
            min_i = i
            for j in range(i + 1, n):
                if nums[j] < nums[min_i]:
                    min_i = j
            # 交换元素
            if i != min_i:
                nums[i], nums[min_i] = nums[min_i], nums[i]
        return nums

    def sortArray(self, nums: list[int]) -> list[int]:
        return self.selectionSort(nums)


# 插入排序（Insertion Sort）

# 基本思想：
# 将数组分为有序区间和无序区间，每次从无序区间取出一个元素插入到有序区间的正确位置。

# 插入排序通过逐步构建有序序列来实现排序，每次插入后有序区间保持有序。

class Solution:
    def insertionSort(self, nums: list[int]) -> list[int]:
        # 遍历无序区间
        for i in range(1, len(nums)):
            temp = nums[i]
            j = i
            # 从右至左遍历有序区间
            while j > 0 and nums[j - 1] > temp:
                # 将大于temp的元素右移
                nums[j] = nums[j - 1]
                j -= 1
            # 插入到正确位置
            nums[j] = temp
        return nums

    def sortArray(self, nums: list[int]) -> list[int]:
        return self.insertionSort(nums)


# 选择排序和插入排序可以认为是互补的
# 一个是保证无序区间“选择”的有序性，另一个保证有序区间“插入”的有序性 


# 希尔排序（Shell Sort）

# 基本思想：
# 通过设定不同的间隔（gap），将数组分组进行插入排序，然后逐步缩小间隔直至为 1，最终完成整个数组的排序。

# 希尔排序算法步骤
# 假设数组长度为 n，算法步骤如下：
    # 1. 设定初始间隔 gap = n / 2。
    # 2. 按间隔将数组分组，对每组进行插入排序。
    # 3. 缩小间隔 gap = gap / 2。
    # 4. 重复步骤 2∼3，直到 gap = 1。
    # 5. 最后对整个数组进行一次插入排序。

class Solution:
    def shellSort(self, nums: list[int]) -> list[int]:
        size = len(nums)
        gap = size // 2  # 初始间隔设为数组长度的一半

        # 不断缩小gap，直到gap为0
        while gap > 0:
            # 从gap位置开始，对每个元素进行组内插入排序
            for i in range(gap, size):
                temp = nums[i]  # 记录当前待插入的元素
                j = i
                # 在组内进行插入排序，将比 temp 大的元素向后移动
                while j >= gap and nums[j - gap] > temp:
                    nums[j] = nums[j - gap]  # 元素后移
                    j -= gap    # 向前跳 gap 步
                nums[j] = temp  # 插入到正确位置
            # 缩小 gap，通常取 gap 的一半
            gap //= 2

        return nums  # 返回排序后的数组

    def sortArray(self, nums: list[int]) -> list[int]:
        """排序接口，调用shellSort方法"""
        return self.shellSort(nums)

# 希尔排序的时间复杂度高度依赖于间隔序列的选择。
# 当采用常见的 gap = gap // 2 间隔序列时，排序过程大约需要 log2(n) 趟，每一趟的操作类似于分组插入排序。
# 每一趟的排序时间复杂度介O(n)和O(n^2)之间，但随着 gap 的减小，实际操作次数逐步减少。
# 综合来看，希尔排序的整体时间复杂度通常介于O(nlogn)和O(n^2)之间，如果间隔序列选择得当，性能可接近O(nlogn)。

# 希尔排序是插入排序的改进版本，通过分组排序减少数据移动次数，提高排序效率。
# 优点：比插入排序更快，空间复杂度低，适合中等规模数据
# 缺点：时间复杂度不稳定，不稳定排序，间隔序列选择影响性能