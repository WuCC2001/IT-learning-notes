# 计算二进制中二进位为 1 的个数
# 不断执行 X & (X-1)，直到X为0
class Solution:
    def hammingWeight(self, n: int) -> int:
        cnt = 0
        while n:
            n = n & (n - 1)
            cnt += 1
        return cnt

