# 只出现一次的数字 II
# 将出现三次的元素换成二进制形式放在一起，其二进制对应位置上，出现 1 的个数一定是 3 的倍数（包括 0 ）。
# 此时，如果在放进来只出现一次的元素，则某些二进制位置上出现 1 的个数就不是 3 的倍数了。 
# 将这些二进制位置上出现 1 的个数不是 3 的倍数位置值置为 1 ，是 3 的倍数则置为 0 。这样对应下来的二进制就是答案所求。
# 感觉这个题目具有推广性：只有1个数出现k次，其余数都出现m次
class Solution:
    def singleNumber(self, nums: list[int]) -> int:
        ans = 0
        # 数值范围为-2**31 ~ 2**31-1
        for i in range(32):
            count = 0
            # 统计每个数位，出现1的次数
            for j in range(len(nums)):
                count += (nums[j] >> i) & 1
            # 如果该数位的1次数不为3的倍数
            if count % 3 != 0:
                # 负数补码+对应正数=1 << n（数值范围），因此：负数补码- 1 << n = 对应负数
                # 数位在最高位上为1，表示其为负数（补码形式）。将负数的补码转换为「负号+原码」的形式
                if i == 31:
                    ans -= (1 << 31)
                else:
                    ans = ans | 1 << i
        return ans

